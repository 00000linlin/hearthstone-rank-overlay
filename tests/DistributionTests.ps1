param([switch]$Integration)
$ErrorActionPreference = 'Stop'
$hsRoot = Split-Path -Parent $PSScriptRoot
$hsVersion = (Get-Content -Raw -LiteralPath (Join-Path $hsRoot 'version.txt')).Trim()
$hsCases = Join-Path $hsRoot ('.qa\distribution-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $hsCases -Force | Out-Null
$hsCanonical = [IO.Path]::GetFullPath($hsCases)
if (!$hsCanonical.StartsWith(([IO.Path]::GetFullPath((Join-Path $hsRoot '.qa')) + '\'), [StringComparison]::OrdinalIgnoreCase)) { throw 'Unexpected test directory' }
function Confirm([bool]$Condition, [string]$Message) { if (!$Condition) { throw "FAIL: $Message" }; "PASS: $Message" }
$hsCompiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
& $hsCompiler /nologo /r:System.Core.dll /main:InstallSafetyTests ("/out:" + (Join-Path $hsCases 'InstallSafetyTests.exe')) (Join-Path $hsRoot 'tools\InstallerGuard.cs') (Join-Path $hsRoot 'tests\InstallSafetyTests.cs')
if ($LASTEXITCODE -ne 0) { throw 'Install safety tests compile failed' }
& (Join-Path $hsCases 'InstallSafetyTests.exe') (Join-Path $hsCases 'native-checks')
if ($LASTEXITCODE -ne 0) { throw 'Install safety tests failed' }

# Rebuild a copied source project against stale artifacts, without touching the
# real dist directory. This guards against hashing old or unrelated packages.
$hsCopy = Join-Path $hsCases 'source'
New-Item -ItemType Directory -Path $hsCopy,(Join-Path $hsCopy 'src'),(Join-Path $hsCopy 'tools'),(Join-Path $hsCopy 'dist') -Force | Out-Null
foreach ($hsFile in @('build.ps1','version.txt','README.md','LICENSE')) { Copy-Item -LiteralPath (Join-Path $hsRoot $hsFile) -Destination $hsCopy }
Get-ChildItem -LiteralPath (Join-Path $hsRoot 'src') -File | Copy-Item -Destination (Join-Path $hsCopy 'src')
foreach ($hsFile in @('IconBuilder.cs','InstallerGuard.cs')) { Copy-Item -LiteralPath (Join-Path $hsRoot 'tools' $hsFile) -Destination (Join-Path $hsCopy 'tools') }
$hsOldSetup = Join-Path $hsCopy "dist\HearthstoneRank-$hsVersion-Setup.exe"
Set-Content -LiteralPath $hsOldSetup -Value 'STALE INSTALLER SENTINEL'
Set-Content -LiteralPath (Join-Path $hsCopy 'dist\unrelated.zip') -Value 'UNRELATED ZIP'
& (Join-Path $hsCopy 'build.ps1') | Out-String | Write-Output
$hsChecksums = @(Get-Content -LiteralPath (Join-Path $hsCopy 'dist\SHA256SUMS.txt'))
Confirm ($hsChecksums.Count -eq 1 -and $hsChecksums[0].EndsWith("HearthstoneRank-$hsVersion-portable.zip")) 'only artifacts generated by this invocation are checksummed'
Confirm ((Get-Content -Raw -LiteralPath $hsOldSetup).Contains('STALE INSTALLER SENTINEL')) 'skipped installer is not overwritten or relabelled'
Confirm (@(Get-ChildItem -LiteralPath (Join-Path $hsCopy 'build') -Directory -Filter 'stage-*').Count -eq 0) 'staging files are cleaned after successful build'
$hsAssembly = [Reflection.AssemblyName]::GetAssemblyName((Join-Path $hsCopy 'dist\HearthstoneRank.exe'))
Confirm ($hsAssembly.Version.ToString() -eq "$hsVersion.0") 'assembly version follows version.txt'
$hsPackagedReadme = Get-Content -Raw -LiteralPath (Join-Path $hsCopy 'dist\HearthstoneRank-README.md')
Confirm ($hsPackagedReadme.Contains('(LICENSE.txt)') -and !$hsPackagedReadme.Contains('(docs/validation.md)')) 'portable README links resolve in the package or online'

if (!$Integration) { return }
$hsRegistry = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\HearthstoneRank'
if (Test-Path -LiteralPath $hsRegistry) { throw 'Existing installation found; integration test refuses to modify it.' }
$hsSetup = Join-Path $hsRoot "dist\HearthstoneRank-$hsVersion-Setup.exe"
if (!(Test-Path -LiteralPath $hsSetup)) { throw 'Build the installer first.' }
function Run-Setup([string]$Target) {
    $hsProcess = Start-Process -FilePath $hsSetup -ArgumentList @('/S',('/D=' + $Target)) -PassThru -Wait -WindowStyle Hidden
    return $hsProcess.ExitCode
}
function Run-Uninstall([string]$Target) {
    # _?= runs the actual uninstaller in place, so its result is not hidden by
    # the normal NSIS temporary-copy launcher's successful process exit.
    $hsProcess = Start-Process -FilePath (Join-Path $Target 'Uninstall.exe') -ArgumentList @('/S',('_?=' + $Target)) -PassThru -Wait -WindowStyle Hidden
    return $hsProcess.ExitCode
}
$hsForeign = Join-Path $hsCases 'foreign'
New-Item -ItemType Directory -Path $hsForeign | Out-Null
$hsSentinel = Join-Path $hsCases 'unexpected-execution.txt'
$hsSource = 'class Sentinel { static void Main() { System.IO.File.WriteAllText(@"' + $hsSentinel.Replace('"','""') + '", "unexpected execution"); } }'
$hsSentinelSource = Join-Path $hsCases 'Sentinel.cs'
Set-Content -LiteralPath $hsSentinelSource -Value $hsSource
& $hsCompiler /nologo /target:exe ("/out:" + (Join-Path $hsForeign 'HearthstoneRank.exe')) $hsSentinelSource
if ($LASTEXITCODE -ne 0) { throw 'Sentinel compile failed' }
$hsForeignDigest = (Get-FileHash -LiteralPath (Join-Path $hsForeign 'HearthstoneRank.exe')).Hash
Confirm ((Run-Setup $hsForeign) -ne 0) 'foreign nonempty installation directory is rejected'
Confirm (!(Test-Path -LiteralPath $hsSentinel)) 'existing destination executable is never run'
Confirm ((Get-FileHash -LiteralPath (Join-Path $hsForeign 'HearthstoneRank.exe')).Hash -eq $hsForeignDigest) 'foreign executable is not overwritten'
$hsLinkedTarget = Join-Path $hsCases 'linked-target'
$hsLinkedParent = Join-Path $hsCases 'junction'
New-Item -ItemType Directory -Path $hsLinkedTarget | Out-Null
New-Item -ItemType Junction -Path $hsLinkedParent -Target $hsLinkedTarget | Out-Null
try { Confirm ((Run-Setup (Join-Path $hsLinkedParent 'child')) -ne 0) 'directory junction ancestor is rejected' }
finally { Remove-Item -LiteralPath $hsLinkedParent }
$hsInstall = Join-Path $hsCases 'installed'
Confirm ((Run-Setup $hsInstall) -eq 0) 'clean per-user installation succeeds'
Confirm ((Get-FileHash -LiteralPath (Join-Path $hsInstall 'HearthstoneRank.exe')).Hash -eq (Get-FileHash -LiteralPath (Join-Path $hsRoot 'dist\HearthstoneRank.exe')).Hash) 'installed payload matches the current build'
Confirm (Test-Path -LiteralPath $hsRegistry) 'uninstall registration is present'
Confirm ((Run-Setup (Join-Path $hsCases 'second-install')) -ne 0) 'a second directory cannot orphan the registered installation'
Set-Content -LiteralPath (Join-Path $hsInstall 'keep.txt') -Value 'Unrelated user data'
$hsLocked = [IO.File]::Open((Join-Path $hsInstall 'HearthstoneRank.exe'),[IO.FileMode]::Open,[IO.FileAccess]::ReadWrite,[IO.FileShare]::None)
try { Confirm ((Run-Uninstall $hsInstall) -ne 0) 'uninstall reports a locked payload as failure' }
finally { $hsLocked.Dispose() }
Confirm ((Test-Path -LiteralPath $hsRegistry) -and (Test-Path -LiteralPath (Join-Path $hsInstall 'Uninstall.exe'))) 'failed uninstall retains its recovery entry'
$hsWrong = Join-Path $hsCases 'copied-uninstaller'
New-Item -ItemType Directory -Path $hsWrong | Out-Null
Copy-Item -LiteralPath (Join-Path $hsInstall 'Uninstall.exe') -Destination $hsWrong
Set-Content -LiteralPath (Join-Path $hsWrong 'LICENSE.txt') -Value 'Foreign license'
Confirm ((Run-Uninstall $hsWrong) -ne 0) 'copied uninstaller refuses an unregistered directory'
Confirm ((Get-Content -Raw -LiteralPath (Join-Path $hsWrong 'LICENSE.txt')).Contains('Foreign license')) 'copied uninstaller preserves foreign files'
Remove-Item -LiteralPath (Join-Path $hsInstall 'HearthstoneRank.exe.config')
Confirm ((Run-Uninstall $hsInstall) -eq 0) 'uninstall remains retryable when one optional payload is already missing'
Confirm (!(Test-Path -LiteralPath $hsRegistry) -and !(Test-Path -LiteralPath (Join-Path $hsInstall 'HearthstoneRank.exe'))) 'successful uninstall removes application and registration'
Confirm (Test-Path -LiteralPath (Join-Path $hsInstall 'keep.txt')) 'uninstall preserves unrelated files'
